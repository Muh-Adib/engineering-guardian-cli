#!/usr/bin/env node

import { Command } from 'commander';

import { initProject, runDoctor, runScan, verifyProject } from './application/commands.js';

const program = new Command();

program
  .name('eg')
  .description('Engineering Guardian CLI for Next.js and Prisma quality analysis')
  .version('0.1.0');

program
  .command('init')
  .description('Create Guardian config and managed AGENTS.md block')
  .action(() => {
    const result = initProject(process.cwd());
    console.log(`Initialized Guardian config at ${result.configPath}`);
    console.log(`Initialized AGENTS instructions at ${result.agentsPath}`);
  });

program
  .command('doctor')
  .description('Inspect project stack and environment')
  .action(() => {
    const result = runDoctor(process.cwd());
    console.log(result.output);
  });

program
  .command('scan')
  .option('--changed', 'scan changed files only')
  .description('Run a repository scan')
  .action((options) => {
    const result = runScan(process.cwd());
    console.log(`Findings: ${result.summary.total}`);
    for (const [severity, count] of Object.entries(result.summary.bySeverity)) {
      console.log(`${severity}: ${count}`);
    }
    for (const finding of result.findings.slice(0, 10)) {
      console.log(`${finding.id} [${finding.severity}] ${finding.title} (${finding.location.file}:${finding.location.line})`);
    }

    if (options.changed) {
      console.log('Changed-file scan mode is scaffolded; Git diff integration is planned for the next iteration.');
    }
  });

program
  .command('explain')
  .requiredOption('--id <id>', 'finding ID to explain')
  .description('Explain a finding without running arbitrary commands')
  .action((options) => {
    console.log(`Explanation for ${options.id}: this finding is generated by the deterministic rule engine and should be reviewed in context before making a change.`);
  });

program
  .command('fix')
  .requiredOption('--id <id>', 'finding ID to propose a repair for')
  .option('--apply', 'apply approved patch')
  .description('Generate a preview-only assisted repair proposal')
  .action((options) => {
    if (options.apply) {
      console.log(`Apply requested for ${options.id}. Approval gate required before any patch is written.`);
      return;
    }

    console.log(`Repair preview for ${options.id}: no patch generated without explicit approval and context validation.`);
  });

program
  .command('verify')
  .description('Report project verification status')
  .action(() => {
    const result = verifyProject(process.cwd());
    console.log(result.status);
    if (result.commands.length) {
      for (const command of result.commands) {
        console.log(command);
      }
    }
  });

program.parse(process.argv);
